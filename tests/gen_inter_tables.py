"""Generate third_party/av1gpu/encoder/apps/inter_tables.h from the AV1 specification source.

Run: python3 tests/gen_inter_tables.py PATH/TO/av1-spec > third_party/av1gpu/encoder/apps/inter_tables.h

The av1-spec repository is https://github.com/AOMediaCodec/av1-spec. Only the default CDFs used by
inter frames, the subpel filters, and the symbol constants they need are emitted.
"""
import pathlib
import re
import sys

TABLES = [
    "Default_Is_Inter_Cdf", "Default_Single_Ref_Cdf", "Default_Comp_Mode_Cdf",
    "Default_New_Mv_Cdf", "Default_Zero_Mv_Cdf", "Default_Ref_Mv_Cdf", "Default_Drl_Mode_Cdf",
    "Default_Mv_Joint_Cdf", "Default_Mv_Class_Cdf", "Default_Mv_Class0_Bit_Cdf",
    "Default_Mv_Class0_Fr_Cdf", "Default_Mv_Class0_Hp_Cdf", "Default_Mv_Fr_Cdf", "Default_Mv_Hp_Cdf",
    "Default_Mv_Sign_Cdf", "Default_Mv_Bit_Cdf", "Default_Inter_Tx_Type_Set1_Cdf", "Default_Inter_Tx_Type_Set2_Cdf", "Default_Inter_Tx_Type_Set3_Cdf",
    "Default_Y_Mode_Cdf", "Default_Comp_Ref_Cdf", "Default_Comp_Bwd_Ref_Cdf",
    "Default_Comp_Ref_Type_Cdf", "Default_Compound_Mode_Cdf", "Default_Txfm_Split_Cdf",
]


def main(root):
    root = pathlib.Path(root)
    symbols = {}
    for line in (root / "03.symbols.md").read_text().splitlines():
        m = re.match(r"\|\s*`(\w+)`\s*\|\s*(-?\d+)\s*\|", line)
        if m:
            symbols[m.group(1)] = int(m.group(2))
    text = (root / "10.additional.tables.md").read_text()
    decoding = (root / "08.decoding.process.md").read_text()
    out = ["// Generated by tests/gen_inter_tables.py from the AV1 specification. Do not edit.",
           "#pragma once", "#include <cstdint>", "", "namespace pft {"]
    used = set()
    bodies = []

    def emit(name, source, ctype):
        m = re.search(r"^\s*" + name + r"((?:\s*\[[^\]]+\])+)\s*=\s*\{", source, re.M)
        if not m:
            raise SystemExit(f"table {name} not found")
        dims = re.findall(r"\[\s*([^\]]+?)\s*\]", m.group(1))
        start = m.end() - 1
        depth = 0
        for i in range(start, len(source)):
            depth += source[i] == "{"
            depth -= source[i] == "}"
            if depth == 0:
                break
        body = source[start:i + 1]
        for d in dims:
            for token in re.findall(r"[A-Z_][A-Z0-9_]*", d):
                used.add(token)
        bodies.append(f"inline constexpr {ctype} {name}" + "".join(f"[{d}]" for d in dims) + " = " + body + ";")

    for name in TABLES:
        emit(name, text, "uint16_t")
    emit("Subpel_Filters", decoding, "int16_t")
    for token in sorted(used):
        if token not in symbols:
            raise SystemExit(f"constant {token} not found")
        out.append(f"constexpr int {token} = {symbols[token]};")
    for extra in ("REF_CAT_LEVEL", "MAX_REF_MV_STACK_SIZE", "MV_BORDER"):
        out.append(f"constexpr int {extra} = {symbols[extra]};")
    out.append("")
    out.extend(bodies)
    out.append("}  // namespace pft")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
